import type { Metadata } from "next";

export const BASE_URL = "https://carsonspriggs.com";
export const SITE_NAME = "Carson Spriggs-Audet";
export const DEFAULT_TITLE =
	"Carson Spriggs-Audet | AI Automation Developer, Montreal";
export const DEFAULT_DESCRIPTION =
	"Carson Spriggs-Audet is a Canada-based AI Automation Software Developer at Qohash, focused on automation, data, and practical software.";
export const DEFAULT_SOCIAL_IMAGE = "/social-card.png";
export const DEFAULT_SOCIAL_IMAGE_ALT =
	"Carson Spriggs-Audet software developer portfolio preview card.";

/** Per-case-study share card, generated by scripts/generate-social-cards.mjs. */
export const caseStudyCard = (slug: string) => `/og/${slug}.jpg`;

// Explicit so Google, Bing and friends use large image previews rather than the
// default "standard" thumbnail (this is what Discover eligibility keys off) and
// stop truncating snippets.
export const ROBOTS: Metadata["robots"] = {
	index: true,
	follow: true,
	googleBot: {
		index: true,
		follow: true,
		"max-image-preview": "large",
		"max-snippet": -1,
		"max-video-preview": -1,
	},
};

export function absoluteUrl(pathname = "/") {
	return new URL(pathname, BASE_URL).toString();
}

/**
 * CollectionPage + ItemList for index pages, so the set of write-ups is
 * machine-readable instead of only being discoverable by crawling links.
 */
export function collectionSchema({
	name,
	pathname,
	description,
	items,
}: {
	name: string;
	pathname: string;
	description: string;
	items: { name: string; url: string }[];
}) {
	return {
		"@type": "CollectionPage",
		"@id": `${absoluteUrl(pathname)}#collection`,
		url: absoluteUrl(pathname),
		name,
		description,
		inLanguage: "en-CA",
		isPartOf: { "@id": `${BASE_URL}#website` },
		mainEntity: {
			"@type": "ItemList",
			numberOfItems: items.length,
			itemListElement: items.map((item, index) => ({
				"@type": "ListItem",
				position: index + 1,
				name: item.name,
				url: item.url,
			})),
		},
	};
}

/**
 * BreadcrumbList node mirroring the visible breadcrumb trail rendered by
 * SiteNav, so the structured data never drifts from what a visitor sees.
 */
export function breadcrumbSchema(trail: { name: string; href?: string }[]) {
	return {
		"@type": "BreadcrumbList",
		itemListElement: trail.map((crumb, index) => ({
			"@type": "ListItem",
			position: index + 1,
			name: crumb.name,
			// Keep the home crumb in the same no-trailing-slash form Next emits
			// for the canonical link, so structured data and the canonical agree.
			...(crumb.href
				? { item: crumb.href === "/" ? BASE_URL : absoluteUrl(crumb.href) }
				: {}),
		})),
	};
}

type MetadataInput = {
	title: string;
	description: string;
	pathname: string;
	keywords?: string[];
	image?: string;
	openGraphType?: "website" | "article";
	publishedTime?: string;
	modifiedTime?: string;
};

export function createPageMetadata({
	title,
	description,
	pathname,
	keywords,
	image = DEFAULT_SOCIAL_IMAGE,
	openGraphType = "website",
	publishedTime,
	modifiedTime,
}: MetadataInput): Metadata {
	const url = absoluteUrl(pathname);
	const socialImage = absoluteUrl(image);

	return {
		title,
		description,
		keywords,
		alternates: {
			canonical: url,
		},
		category: "Software Engineering",
		robots: ROBOTS,
		openGraph: {
			title,
			description,
			url,
			siteName: SITE_NAME,
			locale: "en_CA",
			type: openGraphType,
			images: [
				{
					url: socialImage,
					width: 1200,
					height: 630,
					alt: DEFAULT_SOCIAL_IMAGE_ALT,
				},
			],
			...(publishedTime ? { publishedTime } : {}),
			...(modifiedTime ? { modifiedTime } : {}),
		},
		twitter: {
			card: "summary_large_image",
			title,
			description,
			images: [socialImage],
		},
	};
}
